    function getAppLocale() {
        try {
            return localStorage.getItem('footballMatchCoder_lang') || 'en';
        } catch (e) {
            return 'en';
        }
    }

    function setAppLocale(code) {
        try {
            localStorage.setItem('footballMatchCoder_lang', code);
        } catch (e) {
            /* ignore */
        }
        document.documentElement.lang = code === 'zh-CN' ? 'zh-Hans' : code;
        applyAppLanguage(code);
    }

    function t(key, vars) {
        const locale = getAppLocale();
        const dict = STRINGS[locale] || STRINGS.en;
        let s = dict[key] || STRINGS.en[key] || key;
        if (vars && typeof s === 'string') {
            Object.keys(vars).forEach((k) => {
                s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(vars[k]));
            });
        }
        return s;
    }

    function applyAppLanguage(code) {
        const dict = STRINGS[code] || STRINGS.en;
        document.querySelectorAll('[data-i18n]').forEach((el) => {
            const key = el.getAttribute('data-i18n');
            if (key && dict[key]) el.textContent = dict[key];
        });
        document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (key && dict[key]) el.setAttribute('placeholder', dict[key]);
        });
        document.querySelectorAll('[data-i18n-title]').forEach((el) => {
            const key = el.getAttribute('data-i18n-title');
            if (key && dict[key]) el.setAttribute('title', dict[key]);
        });
        if (dict.pageTitle) document.title = dict.pageTitle;

        const sel = document.getElementById('languageSelect');
        if (sel) sel.value = code;

        window.dispatchEvent(new CustomEvent('app-language-changed', { detail: { locale: code } }));
    }

    window.APP_I18N_STRINGS = STRINGS;
    window.getAppLocale = getAppLocale;
    window.setAppLocale = setAppLocale;
    window.applyAppLanguage = applyAppLanguage;
    window.t = t;

    function initI18nUi() {
        applyAppLanguage(getAppLocale());
        const sel = document.getElementById('languageSelect');
        if (sel) {
            sel.value = getAppLocale();
            sel.addEventListener('change', () => setAppLocale(sel.value));
        }
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', initI18nUi);
    } else {
        initI18nUi();
    }
